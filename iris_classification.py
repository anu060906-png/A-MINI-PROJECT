# ------------------------------------------------------------
# 1. IMPORT LIBRARIES
# ------------------------------------------------------------

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix
)


# ------------------------------------------------------------
# 2. LOAD IRIS DATASET
# ------------------------------------------------------------

iris = load_iris()

X = iris.data
y = iris.target

# Create DataFrame
df = pd.DataFrame(
    iris.data,
    columns=[
        "SepalLengthCm",
        "SepalWidthCm",
        "PetalLengthCm",
        "PetalWidthCm"
    ]
)

# Add target/species column
df["Species"] = [
    iris.target_names[i]
    for i in iris.target
]


# ------------------------------------------------------------
# 3. DATASET OUTPUT
# ------------------------------------------------------------

print("========== DATASET OUTPUT ==========")

print("\nFirst 10 records:")
print(df.head(10))

print("\nDataset shape:")
print(df.shape)

print("\nSpecies distribution:")
print(df["Species"].value_counts())


# ------------------------------------------------------------
# 4. DATASET INFORMATION
# ------------------------------------------------------------

print("\n========== DATASET INFORMATION ==========")

print("\nDataset Information:")
print(df.info())

print("\nStatistical Summary:")
print(df.describe())


# ------------------------------------------------------------
# 5. CHECK FOR MISSING VALUES
# ------------------------------------------------------------

print("\n========== MISSING VALUES ==========")

print(df.isnull().sum())


# ------------------------------------------------------------
# 6. TRAIN-TEST SPLIT
# ------------------------------------------------------------

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("\n========== TRAIN-TEST SPLIT ==========")

print("Total records:", len(X))
print("Training records:", len(X_train))
print("Testing records:", len(X_test))

print("Training percentage:", len(X_train) / len(X) * 100, "%")
print("Testing percentage:", len(X_test) / len(X) * 100, "%")


# ------------------------------------------------------------
# 7. CREATE DECISION TREE MODEL
# ------------------------------------------------------------

model = DecisionTreeClassifier(
    random_state=42
)


# ------------------------------------------------------------
# 8. TRAIN THE MODEL
# ------------------------------------------------------------

model.fit(X_train, y_train)

print("\n========== MODEL TRAINING ==========")

print("Algorithm: Decision Tree Classifier")
print("Training status: Model trained successfully")
print("Number of training samples:", len(X_train))
print("Number of features:", X_train.shape[1])


# ------------------------------------------------------------
# 9. MAKE PREDICTIONS
# ------------------------------------------------------------

y_pred = model.predict(X_test)

print("\n========== PREDICTIONS ==========")

print("Actual values:")
print(y_test)

print("\nPredicted values:")
print(y_pred)


# ------------------------------------------------------------
# 10. CALCULATE ACCURACY
# ------------------------------------------------------------

accuracy = accuracy_score(
    y_test,
    y_pred
)

print("\n========== ACCURACY ==========")

print("Accuracy:", accuracy)
print("Accuracy Percentage:", accuracy * 100, "%")


# ------------------------------------------------------------
# 11. CLASSIFICATION REPORT
# ------------------------------------------------------------

print("\n========== CLASSIFICATION REPORT ==========")

print(
    classification_report(
        y_test,
        y_pred,
        target_names=iris.target_names
    )
)


# ------------------------------------------------------------
# 12. CONFUSION MATRIX
# ------------------------------------------------------------

cm = confusion_matrix(
    y_test,
    y_pred
)

print("\n========== CONFUSION MATRIX ==========")

print(cm)


# ------------------------------------------------------------
# 13. CONFUSION MATRIX VISUALIZATION
# ------------------------------------------------------------

plt.figure(figsize=(7, 5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=iris.target_names,
    yticklabels=iris.target_names
)

plt.xlabel("Predicted Label")
plt.ylabel("True Label")
plt.title("Confusion Matrix")

plt.show()


# ------------------------------------------------------------
# 14. SPECIES DISTRIBUTION GRAPH
# ------------------------------------------------------------

plt.figure(figsize=(7, 5))

species_count = df["Species"].value_counts()

plt.bar(
    species_count.index,
    species_count.values
)

plt.xlabel("Species")
plt.ylabel("Number of Records")
plt.title("Iris Species Distribution")

plt.show()


# ------------------------------------------------------------
# 15. PETAL LENGTH VS PETAL WIDTH
# ------------------------------------------------------------

plt.figure(figsize=(7, 5))

for i in range(3):

    subset = iris.data[
        iris.target == i
    ]

    plt.scatter(
        subset[:, 2],
        subset[:, 3],
        label=iris.target_names[i]
    )

plt.xlabel("Petal Length (cm)")
plt.ylabel("Petal Width (cm)")
plt.title("Petal Length vs Petal Width")

plt.legend()

plt.show()


# ------------------------------------------------------------
# 16. SEPAL LENGTH VS SEPAL WIDTH
# ------------------------------------------------------------

plt.figure(figsize=(7, 5))

for i in range(3):

    subset = iris.data[
        iris.target == i
    ]

    plt.scatter(
        subset[:, 0],
        subset[:, 1],
        label=iris.target_names[i]
    )

plt.xlabel("Sepal Length (cm)")
plt.ylabel("Sepal Width (cm)")
plt.title("Sepal Length vs Sepal Width")

plt.legend()

plt.show()


# ------------------------------------------------------------
# 17. DECISION TREE VISUALIZATION
# ------------------------------------------------------------

plt.figure(figsize=(16, 9))

plot_tree(
    model,
    feature_names=iris.feature_names,
    class_names=iris.target_names,
    filled=True,
    rounded=True,
    fontsize=9
)

plt.title("Decision Tree Classifier")

plt.show()


# ------------------------------------------------------------
# 18. SAMPLE PREDICTION
# ------------------------------------------------------------

new_flower = [
    [5.1, 3.5, 1.4, 0.2]
]

prediction = model.predict(
    new_flower
)

print("\n========== SAMPLE PREDICTION ==========")

print("Input values:")
print("Sepal Length = 5.1 cm")
print("Sepal Width  = 3.5 cm")
print("Petal Length = 1.4 cm")
print("Petal Width  = 0.2 cm")

print(
    "\nPredicted Species:",
    iris.target_names[prediction][0]
)


# ------------------------------------------------------------
# 19. PREDICT MULTIPLE NEW FLOWERS
# ------------------------------------------------------------

new_flowers = [
    [5.1, 3.5, 1.4, 0.2],
    [6.0, 2.9, 4.5, 1.5],
    [6.5, 3.0, 5.5, 1.8]
]

predictions = model.predict(
    new_flowers
)

print("\n========== MULTIPLE SAMPLE PREDICTIONS ==========")

for i in range(len(new_flowers)):

    print(
        "Flower",
        i + 1,
        "->",
        iris.target_names[predictions[i]]
    )